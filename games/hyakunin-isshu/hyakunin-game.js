/* =========================================================
   百人一首⛩️ 固有ロジック
   共通土台(GameShell)のAPIだけを使い、出題・選択・判定を実装。
   POEMSの各要素: [歌番, 歌人, 上の句(漢字3句), 上の句(かな3句), 下の句(漢字2句), 下の句(かな2句)]
   ※10番(蝉丸)のみ上の句が2句構成のため句数は可変で扱う。
   ========================================================= */

const POEM_MAP = new Map(POEMS.map((p) => [p[0], p]));

const shell = new GameShell({
  rootSelector: '#app',
  title: '百人一首⛩️',
  hint: '上の句に続く「下の句」を4枚から選びましょう（タイトル5回タップで激むず）',
  hasScore: true,
  hasTimer: false,
});

let deck = [];
let deckIndex = 0;
let currentPoem = null;
let questionCount = 0;
let correctCount = 0;
let locked = false;

/* ---------- ユーティリティ ---------- */
function shuffle(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = (Math.random() * (i + 1)) | 0;
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function furiganaSpan(kanji, kana) {
  return `<span class="hu-word"><span class="hu-kana">${kana}</span><span class="hu-kanji">${kanji}</span></span>`;
}

function rubyLine(kanjiArr, kanaArr) {
  return kanjiArr.map((k, i) => furiganaSpan(k, kanaArr[i])).join(' ');
}

/* 下の句カード用：句ごとに改行される独立した行として組み立てる（ネイティブrubyの折り返し崩れを回避） */
function choiceLines(kanjiArr, kanaArr) {
  return kanjiArr.map((k, i) => `<div class="hu-choice-line">${furiganaSpan(k, kanaArr[i])}</div>`).join('');
}

/* 激むず：上の句の最初の1文字が同じ歌（実際の競技かるたの「決まり字」的に紛らわしい札）を優先して選ぶ */
function pickDecoys(correctId, hard) {
  const pool = POEMS.filter((p) => p[0] !== correctId);
  if (!hard) return shuffle(pool).slice(0, 3);

  const correct = POEM_MAP.get(correctId);
  const firstChar = correct[3][0][0];
  const rival = shuffle(pool.filter((p) => p[3][0][0] === firstChar));
  const decoys = rival.slice(0, 3);
  if (decoys.length < 3) {
    const rest = shuffle(pool.filter((p) => !decoys.includes(p)));
    decoys.push(...rest.slice(0, 3 - decoys.length));
  }
  return decoys;
}

/* ---------- 出題 ---------- */
function nextPoem() {
  if (deckIndex >= deck.length) {
    deck = shuffle(POEMS.map((p) => p[0]));
    deckIndex = 0;
  }
  return POEM_MAP.get(deck[deckIndex++]);
}

function showQuestion() {
  locked = false;
  const nextRow = shell.board.querySelector('#huNextRow');
  if (nextRow) nextRow.style.display = 'none';
  currentPoem = nextPoem();
  questionCount++;
  const [id, author, kk, ka, sk, sa] = currentPoem;

  shell.board.querySelector('#huPoemNo').textContent = `第${id}番　${author}`;
  shell.board.querySelector('#huKami').innerHTML = rubyLine(kk, ka);

  const decoys = pickDecoys(id, shell.hardMode);
  const choices = shuffle([currentPoem, ...decoys]);
  const choicesEl = shell.board.querySelector('#huChoices');
  choicesEl.innerHTML = '';
  choices.forEach((poem) => {
    const btn = document.createElement('button');
    btn.className = 'hu-choice-card';
    btn.innerHTML = choiceLines(poem[4], poem[5]);
    btn.addEventListener('click', () => onChoose(poem[0] === id, btn));
    choicesEl.appendChild(btn);
  });
  updateToolbar();
}

function updateToolbar() {
  const el = shell.board.querySelector('#huCount');
  if (el) el.textContent = `${questionCount}問中 ${correctCount}問正解`;
}

/* ---------- 判定 ---------- */
function onChoose(isCorrect, btn) {
  if (!shell.running || locked) return;

  if (isCorrect) {
    locked = true;
    correctCount++;
    shell.addScore(10);
    btn.classList.add('hu-correct');
    shell.showPopup(btn, '正解！✨', 'good');
    playCorrectChime();
    spawnSakura();
    updateToolbar();

    // 他の札は選べなくし、正解の歌をじっくり眺められるようにする（自動送りはしない）
    shell.board.querySelectorAll('.hu-choice-card').forEach((el) => { el.disabled = true; });
    shell.board.querySelector('#huNextRow').style.display = 'flex';
  } else {
    btn.classList.add('hu-tried', 'hu-shake');
    btn.disabled = true;
    setTimeout(() => btn.classList.remove('hu-shake'), 400);
    shell.showPopup(btn, 'ちがう札……', 'bad');
    playMissTone();
  }
}

/* 正解音：都節音階（ミ・ファ・ラ・シ）に基づく、雅な上昇フレーズ */
function playCorrectChime() {
  const notes = [659.25, 698.46, 880.0, 987.77];
  notes.forEach((freq, i) => setTimeout(() => shell.playTone(freq, 0.5, 'triangle'), i * 200));
}

/* 不正解音：やわらかい2音（優しめ） */
function playMissTone() {
  shell.playTone(392, 0.12, 'sine');
  setTimeout(() => shell.playTone(330, 0.16, 'sine'), 90);
}

/* 桜吹雪：右上から、薄いピンクの花びらが静かにハラハラ舞い落ちる（少量） */
function spawnSakura() {
  const container = shell.board.querySelector('#huSakuraContainer');
  container.innerHTML = ''; // 前回分を消去

  const petalCount = 14; // カード内表示のため控えめな量

  for (let i = 0; i < petalCount; i++) {
    const petal = document.createElement('div');
    petal.className = 'hu-petal';

    const startLeft = 50 + Math.random() * 50;   // 右上寄り：50%〜100%
    const size = 8 + Math.random() * 6;           // 8px〜14px
    const duration = 2.5 + Math.random() * 2.0;   // 2.5秒〜4.5秒
    const delay = Math.random() * 1.5;            // 降り始めをずらす
    const dx = -(60 + Math.random() * 100);       // 左へ流れる量
    const dy = 220 + Math.random() * 80;          // 落下する縦幅

    petal.style.left = `${startLeft}%`;
    petal.style.width = `${size}px`;
    petal.style.height = `${size * 1.3}px`;
    petal.style.animationDuration = `${duration}s`;
    petal.style.animationDelay = `${delay}s`;
    petal.style.setProperty('--dx', `${dx}px`);
    petal.style.setProperty('--dy', `${dy}px`);

    container.appendChild(petal);
    setTimeout(() => petal.remove(), (duration + delay) * 1000 + 200);
  }
}

/* ---------- 盤面構築 ---------- */
function buildBoard() {
  deck = shuffle(POEMS.map((p) => p[0]));
  deckIndex = 0;
  questionCount = 0;
  correctCount = 0;

  shell.board.className = 's-board hu-board';
  shell.board.innerHTML = `
    <div class="hu-sakura-container" id="huSakuraContainer"></div>
    <div class="hu-toolbar">
      <span id="huCount">0問中 0問正解</span>
      <button class="s-icon-btn-text hu-end-btn" id="huEndBtn">ここまでにする</button>
    </div>
    <div class="hu-kami-wrap">
      <div class="hu-poem-no" id="huPoemNo"></div>
      <div class="hu-kami-card" id="huKami"></div>
    </div>
    <div class="hu-choices" id="huChoices"></div>
    <div class="hu-next-row" id="huNextRow">
      <button class="s-btn hu-next-btn" id="huNextBtn">つぎの歌 →</button>
    </div>
  `;
  shell.board.querySelector('#huEndBtn').addEventListener('click', finishGame);
  shell.board.querySelector('#huNextBtn').addEventListener('click', () => {
    shell.board.querySelector('#huNextRow').style.display = 'none';
    showQuestion();
  });

  showQuestion();
}

function finishGame() {
  if (!shell.running) return;
  shell.end(`おつかれさまでした🌸 ${questionCount}問中 ${correctCount}問正解`);
}

function showPlaceholder() {
  shell.board.className = 's-board';
  shell.board.innerHTML = `
    <div class="hu-placeholder">
      <p>上の句に続く「下の句」を4枚の札から選びましょう。</p>
      <p>時間制限はありません。ゆっくり、まったり楽しんでください。</p>
      <p class="hu-placeholder-start">「スタート」を押すとはじまります</p>
    </div>
  `;
}
showPlaceholder();

/* ---- GameShellのライフサイクルに接続 ---- */
shell.onStart(() => {
  buildBoard();
});
shell.onReset(() => {
  showPlaceholder();
});
shell.onHardModeChange(() => {
  // running中は呼ばれない（GameShell側で保証）。次回スタート時のpickDecoysに反映される。
});
